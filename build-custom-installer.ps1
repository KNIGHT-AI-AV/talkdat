            $env:UV_PYTHON_INSTALL_DIR = Join-Path $Root ".uv-python"
        }
        Invoke-Checked "uv venv" { & $Uv.Source venv --seed $VenvPath }
    } else {
        Invoke-Checked "python venv" { python -m venv $VenvPath }
    }
}

