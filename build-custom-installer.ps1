function Test-UsablePython {
    param([string]$Path)
    if (-not (Test-Path $Path)) { return $false }
    try {
        & $Path --version *> $null
        if ($LASTEXITCODE -ne 0) { return $false }
        & $Path -m pip --version *> $null
        return $LASTEXITCODE -eq 0
    } catch {
        return $false
    }
}

function Invoke-Checked {
    param(
        [string]$Label,
        [scriptblock]$Script
    )
    & $Script
    if ($LASTEXITCODE -ne 0) {
        throw "$Label failed with exit code $LASTEXITCODE"
    }
}

function New-VersionInfoFile {
    param(
        [string]$Path,
        [string]$Version,
        [string]$FileDescription,
        [string]$OriginalFilename
    )
    $VersionParts = [regex]::Matches($Version, "\d+") | ForEach-Object { [int]$_.Value }
    $Numbers = @(0, 0, 0, 0)
    for ($Index = 0; $Index -lt [Math]::Min(4, $VersionParts.Count); $Index++) {
        $Numbers[$Index] = $VersionParts[$Index]
    }
    $NumericVersion = "$($Numbers[0]).$($Numbers[1]).$($Numbers[2]).$($Numbers[3])"
    $Text = @"
# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($($Numbers[0]), $($Numbers[1]), $($Numbers[2]), $($Numbers[3])),
    prodvers=($($Numbers[0]), $($Numbers[1]), $($Numbers[2]), $($Numbers[3])),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904b0', [
        StringStruct('CompanyName', 'Knight AI+AV'),
        StringStruct('FileDescription', '$FileDescription'),
        StringStruct('FileVersion', '$NumericVersion'),
        StringStruct('InternalName', 'Talk Dat!'),
        StringStruct('OriginalFilename', '$OriginalFilename'),
        StringStruct('ProductName', 'Talk Dat!'),
        StringStruct('ProductVersion', '$Version')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path) | Out-Null
    Set-Content -LiteralPath $Path -Value $Text -Encoding UTF8
}

$BuildMutex = [System.Threading.Mutex]::new($false, "Local\TalkDatCustomInstallerBuild")
$HasBuildMutex = $false

try {
    try {
        $HasBuildMutex = $BuildMutex.WaitOne(0)
    } catch [System.Threading.AbandonedMutexException] {
        $HasBuildMutex = $true
    }

    if (-not $HasBuildMutex) {
        throw "Another Talk Dat! installer build is already running. Wait for it to finish before starting a new build."
    }

# A running instance of the BUILD PAYLOAD locks PyInstaller's output. Match
# its exact executable path so preparing a release never interrupts the
# installed app. Own the build mutex before stopping or deleting anything.
if (-not $SkipExeBuild) {
    $ResolvedRoot = (Resolve-Path -LiteralPath $Root).Path.TrimEnd('\')
    $ResolvedAppDir = [IO.Path]::GetFullPath($AppDir)
    $ExpectedAppDir = Join-Path $ResolvedRoot 'dist\Talk Dat!'
    if (-not [string]::Equals($ResolvedAppDir, $ExpectedAppDir, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to clean a build payload outside this repository: $ResolvedAppDir"
    }
    foreach ($PayloadPath in @((Join-Path $ResolvedRoot 'dist'), $ResolvedAppDir)) {
        if ((Test-Path -LiteralPath $PayloadPath) -and
            ((Get-Item -LiteralPath $PayloadPath).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
            throw "Refusing to clean a linked build directory: $PayloadPath"
        }
    }
    $ResolvedAppExe = Join-Path $ResolvedAppDir 'Talk Dat!.exe'
    Get-Process "Talk Dat!" -ErrorAction SilentlyContinue |
        Where-Object { $_.Path -and [string]::Equals($_.Path, $ResolvedAppExe, [StringComparison]::OrdinalIgnoreCase) } |
        Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 2
    if (Test-Path -LiteralPath $ResolvedAppDir) {
        Remove-Item -LiteralPath $ResolvedAppDir -Recurse -Force
    }
}
# End build-payload cleanup

if (-not (Test-UsablePython $Python)) {
    if (Test-Path $VenvPath) {
        $ResolvedRoot = (Resolve-Path $Root).Path
        $ResolvedVenv = (Resolve-Path $VenvPath).Path
        if (-not $ResolvedVenv.StartsWith($ResolvedRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
            throw "Refusing to remove virtualenv outside repo: $ResolvedVenv"
        }
        Remove-Item -LiteralPath $ResolvedVenv -Recurse -Force
    }
    $Uv = Get-Command uv -ErrorAction SilentlyContinue
    if ($Uv) {
        if (-not $env:UV_CACHE_DIR) {
            $env:UV_CACHE_DIR = Join-Path $Root ".uv-cache"
        }
